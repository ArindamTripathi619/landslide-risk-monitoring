class TranslationService {
  private currentLang = 'en';
  private listeners: (() => void)[] = [];

  async init() {
    const lang = await AsyncStorage.getItem('language');
    if (lang && translations[lang as keyof typeof translations]) {
      this.currentLang = lang;
    }
  }

  setLanguage(lang: string) {
    if (translations[lang as keyof typeof translations]) {
      this.currentLang = lang;
      AsyncStorage.setItem('language', lang);
      this.listeners.forEach((l) => l());
    }
  }

  getLanguage(): string {
    return this.currentLang;
  }

  t(key: TranslationKey): string {
    const lang = this.currentLang as keyof typeof translations;
    return translations[lang]?.[key] || translations.en[key] || key;
  }

  onLanguageChange(callback: () => void) {
    this.listeners.push(callback);
    return () => {
      this.listeners = this.listeners.filter((l) => l !== callback);
    };
  }
}

export const translations_data = translations;
export default new TranslationService();
